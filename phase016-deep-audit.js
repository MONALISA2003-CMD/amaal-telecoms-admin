import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const server=read('server.js');
const commerce=read('commerce-phase016.sql');
const lib=read('apps/public-web/lib/commerce.ts');
const cart=read('apps/public-web/app/cart/page.tsx');
const checkout=read('apps/public-web/app/checkout/page.tsx');
const drawer=read('apps/public-web/components/CartDrawer.tsx');
const admin=read('apps/business-admin/components/CommerceLifecyclePanel.tsx');
const compat=read('apps/public-web/components/CompatibilityPanel.tsx');
const product=read('apps/business-admin/components/ProductAdmin.tsx');
const checks=[];
const ok=(name,condition,detail='')=>{checks.push({name,ok:Boolean(condition),detail});if(condition)console.log(`PASS ${name}`);else console.error(`FAIL ${name}${detail?`: ${detail}`:''}`)};
ok('phase016 migration present',commerce.includes('CREATE TABLE IF NOT EXISTS commerce_carts'));
ok('migration has no destructive statements',!/^\s*(DROP|TRUNCATE|DELETE FROM)\b/im.test(commerce));
ok('server runs phase016 migration',server.includes("commerce-phase016.sql"));
ok('server cart GET/POST/PATCH/DELETE routes', ['/api/public/cart','/api/public/cart/items','/api/public/cart/items/:id'].every(x=>server.includes(x)));
ok('server validates published variant before cart add',server.includes('validatePublicCartVariant')&&server.includes("website_visibility='Published'"));
ok('cart uses server sync',lib.includes('syncServerCart')&&cart.includes('syncServerCart'));
ok('cart server mutations',lib.includes('addServerCart')&&lib.includes('updateServerCart')&&lib.includes('removeServerCart'));
ok('checkout does not invoke payment intent',!checkout.includes('/api/public/orders/payment-intent'));
ok('checkout remains server-authoritative',server.includes("amaal_effective_variant_price_qty")&&server.includes('reserveStock'));
ok('price alerts persisted',server.includes('product_price_alerts')&&server.includes('/price-alert'));
ok('stock alerts persisted',server.includes('product_stock_alerts')&&server.includes('/back-in-stock'));
ok('price drop notification hook',server.includes("status='Triggered'")&&server.includes('Price update'));
ok('back in stock notification hook',server.includes('Back in stock')&&server.includes('stock-alert:'));
ok('normalized attributes persisted',commerce.includes('product_attributes')&&server.includes('/attributes'));
ok('search synonyms persisted',commerce.includes('search_synonyms')&&server.includes('synonyms'));
ok('review helpful votes persisted',commerce.includes('review_helpful_votes')&&server.includes('/api/public/reviews/:id/helpful'));
ok('reorder is customer scoped',server.includes("/api/public/account/reorder/:orderNo")&&server.includes('customer_id=$2'));
ok('commerce analytics persisted',commerce.includes('commerce_events')&&server.includes('/api/public/commerce/event'));
ok('admin lifecycle surface wired',admin.includes('/api/catalog/commerce/lifecycle')&&product.includes('Product intelligence'));
ok('compatibility rules persisted and surfaced',commerce.includes('product_compatibility_rules')&&server.includes('/api/public/products/:slug/compatible')&&server.includes('/api/catalog/products/:id/compatibility')&&compat.includes('/compatible'));
ok('raw img scan clean',!/<img\s/i.test(cart+drawer));
ok('payment providers remain presentation only',checkout.includes('Payment processing will be connected')||checkout.includes('configured payment gateway'));
const failures=checks.filter(x=>!x.ok);
console.log(JSON.stringify({generatedAt:new Date().toISOString(),checks,pass:checks.length-failures.length,failures},null,2));
process.exitCode=failures.length?1:0;
