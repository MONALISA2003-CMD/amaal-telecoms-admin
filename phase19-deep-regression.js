import fs from 'fs';
const root=new URL('./',import.meta.url);
const server=fs.readFileSync(new URL('server.js',root),'utf8');
const engine=fs.readFileSync(new URL('./apps/business-admin/app/api/engine/[...path]/route.ts',root),'utf8');
const roleAudit=fs.readFileSync(new URL('role-permission-regression.js',root),'utf8');
const checks=[];
const pass=(name)=>{checks.push({name,ok:true});console.log('PASS:',name)};
const fail=(name)=>{checks.push({name,ok:false});console.error('FAIL:',name)};
if(/Access-Control-Allow-Origin['"]\s*,\s*['"]\*/.test(server)) fail('No wildcard CORS'); else pass('No wildcard CORS');
if(roleAudit.includes("'/api/recovery/status'") && roleAudit.includes("'/api/public'")) pass('Recovery status explicitly classified as public'); else fail('Recovery status public allow-list missing');
if(server.includes("res.status(403).json({error:'CSRF validation failed'})")) pass('CSRF enforcement present'); else fail('CSRF enforcement missing');
if(server.includes("const mfaEnforced=MFA_LOGIN_ENABLED")) pass('MFA login path preserved without modification'); else fail('MFA login path missing');
if(engine.includes('AbortController') && engine.includes('15000')) pass('Business Admin engine timeout present'); else fail('Business Admin engine timeout missing');
if(server.includes("UPDATE products SET status='Archived',website_visibility='Hidden'")) pass('Product removal is safe archive'); else fail('Product safe archive missing');
const bad=checks.filter(x=>!x.ok); console.log(JSON.stringify({checks,failures:bad.length},null,2)); if(bad.length) process.exitCode=1;
